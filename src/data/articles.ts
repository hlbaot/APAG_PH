// Helper tìm bài viết theo slug (hỗ trợ match chính xác hoặc match một phần, luôn có fallback an toàn)
export function getArticleBySlug(slug: string): Article | undefined {
  if (!slug) return mockArticles[0];
  const exact = mockArticles.find((art) => art.slug === slug);
  if (exact) return exact;
  const partial = mockArticles.find(
    (art) => art.slug.includes(slug) || slug.includes(art.slug)
  );
  if (partial) return partial;
  return mockArticles[0];
}

// Lấy danh sách bài viết mới nhất
export function getLatestArticles(limit = 5): Article[] {
  return [...mockArticles].slice(0, limit);
}
